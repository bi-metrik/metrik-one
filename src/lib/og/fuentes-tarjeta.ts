/**
 * Las tres fuentes de la tarjeta OG, en TTF estatico y recortado.
 *
 * ¿Por que no se reusan los archivos de `src/app/fonts`? Porque Satori, el motor
 * detras de `next/og`, NO lee woff2, y el repo las autoaloja SOLO en woff2
 * variable. Estos binarios salen de ESOS MISMOS archivos: se fija la instancia
 * que el diseno usa y se recorta a los caracteres que la tarjeta imprime, con
 * lo que las tres juntas pesan 13028 bytes en vez de ~200 KB.
 *
 * Van en base64 y no como archivos sueltos a proposito: el handler los necesita
 * en tiempo de ejecucion y asi no depende de que el empaquetado arrastre un
 * binario desde el disco.
 *
 * Se regeneran con (desde la raiz del repo, requiere fontTools):
 *
 *   pyftsubset src/app/fonts/<familia>.woff2 --text="<los caracteres>" \
 *     --output-file=<salida>.ttf --layout-features= --no-hinting --notdef-outline
 *   fonttools varLib.instancer -o <salida>.ttf <salida>.ttf wght=400 [opsz=56]
 *
 * Las tres familias son SIL OFL 1.1 y este archivo REDISTRIBUYE obra derivada
 * (subconjunto e instancia), asi que el aviso viaja con ella, igual que en
 * `layout.tsx`:
 *
 *   Schibsted Grotesk : Copyright 2023 The Schibsted Grotesk Project Authors
 *     https://github.com/schibsted/schibsted-grotesk
 *   Newsreader : Copyright 2019 The Newsreader Project Authors
 *     https://github.com/productiontype/Newsreader
 *   Martian Mono : Copyright 2022 The Martian Mono Project Authors
 *     https://github.com/evilmartians/mono
 *
 *   Los tres bajo SIL Open Font License 1.1 : https://scripts.sil.org/OFL
 */

function desdeBase64(b64: string): ArrayBuffer {
  const limpio = b64.replace(/\s/g, '')
  const binario = atob(limpio)
  const bytes = new Uint8Array(binario.length)
  for (let i = 0; i < binario.length; i++) bytes[i] = binario.charCodeAt(i)
  return bytes.buffer
}

